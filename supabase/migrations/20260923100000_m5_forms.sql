create or replace function public.app_save_form_settings(
  p_form uuid,
  p_is_open boolean,
  p_closes_at timestamptz,
  p_response_cap integer,
  p_audience text,
  p_group uuid,
  p_event uuid,
  p_shared boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor public.app_accounts;
  v_form public.forms;
  v_group uuid := p_group;
  v_event_group uuid;
