/*
 * Whether a form takes a new response right now: 'open', 'closed' or 'full'.
 * Closed wins over full, because "this form is closed" is the truer sentence
 * when both are so.
 */
create or replace function public.app_form_state(p_form public.forms)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when not p_form.is_open then 'closed'
    when p_form.closes_at is not null and p_form.closes_at <= pg_catalog.now() then 'closed'
    when p_form.response_cap is not null
      and (select pg_catalog.count(*) from public.form_responses r where r.form_id = p_form.id)
        >= p_form.response_cap then 'full'
    else 'open'
  end;
$$;

/*
 * The questions, as a caller sent them, made safe to store.
 *
 * Refuses with a sentence anything that would make a form unanswerable or
 * unreadable — an unknown type, two questions with one id, the same directory
 * fact asked twice — and quietly tidies what is merely untidy: blank and
 * repeated choices are dropped, help text is cut at 500 characters. An empty
 * label is allowed, because the builder saves while somebody is still typing;
 * the page calls such a question "Untitled question".
 */
create or replace function public.app_form_clean_fields(p_fields jsonb)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_out jsonb := '[]'::jsonb;
  v_field jsonb;
  v_id text;
  v_type text;
  v_label text;
  v_help text;
  v_required boolean;
  v_options jsonb;
  v_clean jsonb;
  v_option jsonb;
  v_text text;
  v_directory text;
  v_ids text[] := '{}';
  v_directories text[] := '{}';
  v_at integer := 0;
begin
  if p_fields is null then
    return '[]'::jsonb;
  end if;
  if pg_catalog.jsonb_typeof(p_fields) <> 'array' then
    raise exception 'Send the questions as a list.' using errcode = 'check_violation';
  end if;
  if pg_catalog.jsonb_array_length(p_fields) > 60 then
    raise exception 'A form has 60 questions at most.' using errcode = 'check_violation';
  end if;

  for v_field in select e.value from pg_catalog.jsonb_array_elements(p_fields) e loop
    v_at := v_at + 1;
    if pg_catalog.jsonb_typeof(v_field) <> 'object' then
      raise exception 'Question % is not a question.', v_at using errcode = 'check_violation';
    end if;

    v_id := coalesce(v_field ->> 'id', '');
    if v_id !~ '^[a-z0-9]{1,16}$' then
      raise exception 'Question % has no usable id.', v_at using errcode = 'check_violation';
    end if;
    if v_id = any(v_ids) then
      raise exception 'Two questions share the id %.', v_id using errcode = 'check_violation';
    end if;

    v_type := coalesce(v_field ->> 'type', '');
    if v_type not in (
      'short_text', 'long_text', 'single_choice', 'multi_choice', 'dropdown',
      'number', 'date', 'yes_no', 'signature', 'directory'
    ) then
      raise exception 'Question % has a type this form does not know.', v_at
        using errcode = 'check_violation';
    end if;

    v_label := pg_catalog.btrim(coalesce(v_field ->> 'label', ''));
    if pg_catalog.length(v_label) > 200 then
      raise exception 'A question is 200 characters at most.' using errcode = 'check_violation';
    end if;
    v_help := pg_catalog.left(pg_catalog.btrim(coalesce(v_field ->> 'help', '')), 500);
    v_required := case
      when pg_catalog.jsonb_typeof(v_field -> 'required') = 'boolean'
        then (v_field ->> 'required')::boolean
      else false
    end;

    v_clean := null;
    if v_type in ('single_choice', 'multi_choice', 'dropdown') then
      v_options := coalesce(v_field -> 'options', '[]'::jsonb);
      if pg_catalog.jsonb_typeof(v_options) <> 'array' then
        raise exception 'Question % needs its choices as a list.', v_at using errcode = 'check_violation';
      end if;
      if pg_catalog.jsonb_array_length(v_options) > 50 then
        raise exception 'A question has 50 choices at most.' using errcode = 'check_violation';
      end if;
      v_clean := '[]'::jsonb;
      for v_option in select o.value from pg_catalog.jsonb_array_elements(v_options) o loop
        if pg_catalog.jsonb_typeof(v_option) <> 'string' then
          continue;
        end if;
        v_text := pg_catalog.btrim(v_option #>> '{}');
        if v_text = '' or v_clean ? v_text then
          continue;
        end if;
        if pg_catalog.length(v_text) > 120 then
          raise exception 'A choice is 120 characters at most.' using errcode = 'check_violation';
        end if;
        v_clean := v_clean || pg_catalog.jsonb_build_array(v_text);
      end loop;
    end if;

    v_directory := null;
    if v_type = 'directory' then
      v_directory := coalesce(v_field ->> 'directory', '');
      if v_directory not in (
        'full_name', 'external_id', 'email', 'class_of', 'official_class',
        'guardian_name', 'guardian_phone'
      ) then
        raise exception 'Question % asks the directory for something it does not hold.', v_at
          using errcode = 'check_violation';
      end if;
      if v_directory = any(v_directories) then
        raise exception 'The form already asks for that from the directory.'
          using errcode = 'check_violation';
      end if;
      v_directories := v_directories || v_directory;
    end if;

    v_ids := v_ids || v_id;
    v_out := v_out || pg_catalog.jsonb_build_array(pg_catalog.jsonb_strip_nulls(pg_catalog.jsonb_build_object(
      'id', v_id,
      'type', v_type,
      'label', v_label,
      'help', v_help,
      'required', v_required,
      'options', v_clean,
      'directory', v_directory
    )));
  end loop;

  return v_out;
end;
$$;

/* One directory fact, as a form asks for it. */
create or replace function public.app_form_directory_value(p_person public.requesters, p_key text)
returns text
language sql
stable
set search_path = ''
as $$
  select nullif(pg_catalog.btrim(coalesce(case p_key
    when 'full_name' then p_person.display_name
    when 'external_id' then p_person.external_id
    when 'email' then p_person.email
    when 'class_of' then p_person.class_of
    when 'official_class' then p_person.official_class
    when 'guardian_name' then p_person.guardian_name
    when 'guardian_phone' then p_person.guardian_phone
  end, '')), '');
$$;

/*
 * What a matched respondent sees filled in: the directory's answer to every
 * directory question on THIS form and nothing else, with the guardian's phone
 * masked to its last four digits. Nothing the form does not ask for leaves the
 * database, and the phone never leaves it whole.
 */
create or replace function public.app_form_prefill(p_form public.forms, p_person public.requesters)
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
  v_prefill jsonb := '{}'::jsonb;
  v_masked jsonb := '{}'::jsonb;
  v_field jsonb;
  v_value text;
  v_digits text;
begin
  for v_field in
    select e.value from pg_catalog.jsonb_array_elements(p_form.fields) e
    where e.value ->> 'type' = 'directory'
  loop
    if v_field ->> 'directory' = 'guardian_phone' then
      v_digits := pg_catalog.regexp_replace(coalesce(p_person.guardian_phone, ''), '\D', '', 'g');
      if pg_catalog.length(v_digits) >= 4 then
        v_masked := v_masked || pg_catalog.jsonb_build_object(
          v_field ->> 'id',
          '••• ••• ' || pg_catalog.right(v_digits, 4)
        );
      end if;
      continue;
    end if;

    v_value := public.app_form_directory_value(p_person, v_field ->> 'directory');
    if v_value is not null then
      v_prefill := v_prefill || pg_catalog.jsonb_build_object(v_field ->> 'id', v_value);
    end if;
  end loop;

  return pg_catalog.jsonb_build_object('prefill', v_prefill, 'masked', v_masked);
end;
$$;

/* "Jordan", for the greeting. The first name, or the first word of the name. */
create or replace function public.app_form_first_name(p_person public.requesters)
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(
    nullif(pg_catalog.btrim(coalesce(p_person.first_name, '')), ''),
    pg_catalog.split_part(pg_catalog.btrim(coalesce(p_person.display_name, '')), ' ', 1)
  );
$$;

/*
 * The answers, as a respondent sent them, checked against the questions.
 *
 * Answers to questions the form does not ask are dropped. Every answer is
 * checked against its type — a choice has to be one of the choices, a date a
 * real date, a number a number — and a required question left empty refuses
 * the whole response with a sentence naming it. A directory question answered
 * `{"keep": true}` takes the directory's own value, which is how a masked phone
 * number is kept without ever having been shown; one answered with text that
 * differs from the directory is listed in `changed`.
 *
 * Returns {answers: {...}, changed: [...]}.
 */
create or replace function public.app_form_clean_answers(
  p_form public.forms,
  p_answers jsonb,
  p_person public.requesters
)
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
  v_answers jsonb := '{}'::jsonb;
  v_changed jsonb := '[]'::jsonb;
  v_given jsonb;
  v_field jsonb;
  v_id text;
  v_type text;
  v_label text;
  v_raw jsonb;
  v_text text;
  v_value jsonb;
  v_directory text;
  v_limit integer;
  v_date date;
begin
  v_given := coalesce(p_answers, '{}'::jsonb);
  if pg_catalog.jsonb_typeof(v_given) <> 'object' then
    raise exception 'Send the answers as an object.' using errcode = 'check_violation';
  end if;
  if pg_catalog.length(v_given::text) > 200000 then
    raise exception 'Those answers are too long to take.' using errcode = 'check_violation';
  end if;

  for v_field in select e.value from pg_catalog.jsonb_array_elements(p_form.fields) e loop
    v_id := v_field ->> 'id';
    v_type := v_field ->> 'type';
    v_label := coalesce(nullif(v_field ->> 'label', ''), 'Untitled question');
    v_raw := v_given -> v_id;
    if v_raw is not null and pg_catalog.jsonb_typeof(v_raw) = 'null' then
      v_raw := null;
    end if;
    v_value := null;

    if v_type = 'directory' then
      v_directory := case
        when p_person.id is not null
          then public.app_form_directory_value(p_person, v_field ->> 'directory')
      end;
      if v_raw is null then
        v_text := null;
      elsif pg_catalog.jsonb_typeof(v_raw) = 'object' and (v_raw ->> 'keep') = 'true' then
        v_text := v_directory;
      elsif pg_catalog.jsonb_typeof(v_raw) = 'string' then
        v_text := pg_catalog.btrim(v_raw #>> '{}');
        if pg_catalog.length(v_text) > 300 then
          raise exception '"%" is 300 characters at most.', v_label using errcode = 'check_violation';
        end if;
        if v_directory is not null and v_text <> '' and (
          case when v_field ->> 'directory' = 'guardian_phone'
            then pg_catalog.regexp_replace(v_text, '\D', '', 'g')
              <> pg_catalog.regexp_replace(v_directory, '\D', '', 'g')
            else pg_catalog.lower(v_text) <> pg_catalog.lower(v_directory)
          end
        ) then
          v_changed := v_changed || pg_catalog.jsonb_build_array(v_id);
        end if;
      else
        raise exception 'Answer "%" with text.', v_label using errcode = 'check_violation';
      end if;
      if nullif(v_text, '') is not null then
        v_value := pg_catalog.to_jsonb(v_text);
      end if;

    elsif v_type in ('short_text', 'long_text') then
      if v_raw is not null then
        if pg_catalog.jsonb_typeof(v_raw) <> 'string' then
          raise exception 'Answer "%" with text.', v_label using errcode = 'check_violation';
        end if;
        v_text := pg_catalog.btrim(v_raw #>> '{}');
        v_limit := case when v_type = 'short_text' then 500 else 5000 end;
        if pg_catalog.length(v_text) > v_limit then
          raise exception '"%" is % characters at most.', v_label, v_limit using errcode = 'check_violation';
        end if;
        if v_text <> '' then
          v_value := pg_catalog.to_jsonb(v_text);
        end if;
      end if;

    elsif v_type = 'number' then
      if v_raw is not null then
        v_text := pg_catalog.btrim(v_raw #>> '{}');
        if v_text <> '' then
          if v_text !~ '^-?[0-9]{1,12}(\.[0-9]{1,6})?$' then
            raise exception 'Answer "%" with a number.', v_label using errcode = 'check_violation';
          end if;
          v_value := pg_catalog.to_jsonb(v_text::numeric);
        end if;
      end if;

    elsif v_type = 'date' then
      if v_raw is not null then
        v_text := pg_catalog.btrim(v_raw #>> '{}');
        if v_text <> '' then
          if v_text !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then
            raise exception 'Answer "%" with a real date.', v_label using errcode = 'check_violation';
          end if;
          -- The cast is the calendar: 2026-02-30 is refused by it, and the
          -- refusal is turned into the sentence rather than a SQL error.
          begin
            v_date := v_text::date;
          exception
            when others then
              raise exception 'Answer "%" with a real date.', v_label using errcode = 'check_violation';
          end;
          v_value := pg_catalog.to_jsonb(v_text);
        end if;
      end if;

    elsif v_type = 'yes_no' then
      if v_raw is not null then
        if pg_catalog.jsonb_typeof(v_raw) = 'boolean' then
          v_value := v_raw;
        elsif pg_catalog.lower(v_raw #>> '{}') in ('yes', 'true') then
          v_value := 'true'::jsonb;
        elsif pg_catalog.lower(v_raw #>> '{}') in ('no', 'false') then
          v_value := 'false'::jsonb;
        elsif pg_catalog.btrim(v_raw #>> '{}') <> '' then
          raise exception 'Answer "%" with yes or no.', v_label using errcode = 'check_violation';
        end if;
      end if;

    elsif v_type in ('single_choice', 'dropdown') then
      if v_raw is not null then
        v_text := pg_catalog.btrim(v_raw #>> '{}');
        if v_text <> '' then
          if pg_catalog.jsonb_typeof(v_raw) <> 'string'
             or not (coalesce(v_field -> 'options', '[]'::jsonb) ? v_text) then
            raise exception 'Choose one of the choices for "%".', v_label using errcode = 'check_violation';
          end if;
          v_value := pg_catalog.to_jsonb(v_text);
        end if;
      end if;

    elsif v_type = 'multi_choice' then
      if v_raw is not null then
        if pg_catalog.jsonb_typeof(v_raw) <> 'array' or exists (
          select 1 from pg_catalog.jsonb_array_elements(v_raw) c
          where pg_catalog.jsonb_typeof(c.value) <> 'string'
             or not (coalesce(v_field -> 'options', '[]'::jsonb) ? (c.value #>> '{}'))
        ) then
          raise exception 'Choose from the choices for "%".', v_label using errcode = 'check_violation';
        end if;
        -- Kept in the order the form lists them, whatever order they arrived in.
        select pg_catalog.jsonb_agg(o.value order by o.ordinality)
        into v_value
        from pg_catalog.jsonb_array_elements_text(coalesce(v_field -> 'options', '[]'::jsonb))
          with ordinality as o(value, ordinality)
        where v_raw ? o.value;
      end if;

    elsif v_type = 'signature' then
      if v_raw is not null then
        v_text := pg_catalog.btrim(v_raw #>> '{}');
        if v_text <> '' then
          if pg_catalog.jsonb_typeof(v_raw) <> 'string'
             or pg_catalog.length(v_text) > 20000
             or v_text !~ '^[ML0-9 .-]+$' then
            raise exception 'That signature could not be read. Clear it and sign again.'
              using errcode = 'check_violation';
          end if;
          v_value := pg_catalog.to_jsonb(v_text);
        end if;
      end if;
    end if;

    if v_value is null then
      if coalesce((v_field ->> 'required')::boolean, false) then
        raise exception 'Answer "%".', v_label using errcode = 'check_violation';
      end if;
    else
      v_answers := v_answers || pg_catalog.jsonb_build_object(v_id, v_value);
    end if;
  end loop;

  return pg_catalog.jsonb_build_object('answers', v_answers, 'changed', v_changed);
end;
$$;

/*
 * Stores one response and does what the form is linked to.
 *
 * A matched person who has answered before has their answers replaced rather
 * than a second row added. A linked group gains them as a member; a linked
 * event marks them present. Both are "already true is not an error", exactly
 * as the group screens treat them.
 */
create or replace function public.app_form_record_response(
  p_form public.forms,
  p_person uuid,
  p_clean jsonb,
  p_via text,
  p_by uuid
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_existing uuid;
  v_id uuid;
  v_updated boolean := false;
  v_changed text[];
begin
  v_changed := array(select pg_catalog.jsonb_array_elements_text(coalesce(p_clean -> 'changed', '[]'::jsonb)));

  if p_person is not null then
    select r.id into v_existing
    from public.form_responses r
    where r.form_id = p_form.id and r.requester_id = p_person
    for update;
  end if;

  if v_existing is not null then
    update public.form_responses r
    set answers = p_clean -> 'answers',
        changed = v_changed,
        via = p_via,
        recorded_by = p_by,
        submitted_at = pg_catalog.now()
    where r.id = v_existing;
    v_id := v_existing;
    v_updated := true;
  else
    insert into public.form_responses (form_id, requester_id, answers, changed, via, recorded_by)
    values (p_form.id, p_person, p_clean -> 'answers', v_changed, p_via, p_by)
    returning id into v_id;
  end if;

  if p_person is not null and p_form.group_id is not null then
    insert into public.people_group_members (group_id, requester_id, added_by)
    values (p_form.group_id, p_person, p_by)
    on conflict do nothing;
    if found then
      update public.people_groups g set updated_at = pg_catalog.now() where g.id = p_form.group_id;
    end if;
  end if;

  if p_person is not null and p_form.event_id is not null then
    -- The membership is still the authority: somebody is marked present only
    -- at an event of a group they are in. With the form linked to the event's
    -- own group, the insert above has just made that true.
    if exists (
      select 1
      from public.group_events e
      join public.people_group_members m on m.group_id = e.group_id and m.requester_id = p_person
      where e.id = p_form.event_id
    ) then
      insert into public.group_attendance (event_id, requester_id, marked_by)
      values (p_form.event_id, p_person, p_by)
      on conflict do nothing;
    end if;
  end if;

  return pg_catalog.jsonb_build_object('id', v_id, 'updated', v_updated);
end;
$$;

/* The caller, as a hash: the forwarded client address, never stored whole. */
create or replace function public.app_form_client_key()
returns text
language sql
stable
set search_path = ''
as $$
  select pg_catalog.encode(extensions.digest(coalesce(
    nullif(pg_catalog.left(pg_catalog.btrim(public.app_request_headers() ->> 'x-edison-client'), 200), ''),
    nullif(pg_catalog.btrim(pg_catalog.split_part(public.app_request_headers() ->> 'x-forwarded-for', ',', 1)), ''),
    'unknown'
  ), 'sha256'), 'hex');
$$;

/*
 * Whether this caller, or this form as a whole, has run out of tries for the
 * next fifteen minutes. Ten wrong identities per caller and 150 per form;
 * thirty open-form responses per caller and 600 per form.
 */
create or replace function public.app_form_throttled(p_form uuid, p_key text, p_kind text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (
      select pg_catalog.count(*)
      from public.form_identity_attempts a
      where a.form_id = p_form and a.kind = p_kind and a.client_key = p_key
        and a.at > pg_catalog.now() - interval '15 minutes'
    ) >= case when p_kind = 'miss' then 10 else 30 end
    or (
      select pg_catalog.count(*)
      from public.form_identity_attempts a
      where a.form_id = p_form and a.kind = p_kind
        and a.at > pg_catalog.now() - interval '15 minutes'
    ) >= case when p_kind = 'miss' then 150 else 600 end;
$$;

/*
 * The one person an email and an id both name, or nobody.
 *
 * Both have to match the SAME record, and the answer is the same NULL whether
 * neither, one or the other matched. Archived people are not matched: somebody
 * who has left is not signing up for next month's trip.
 */
create or replace function public.app_form_match_identity(p_email text, p_external_id text)
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_email text := pg_catalog.lower(pg_catalog.btrim(coalesce(p_email, '')));
  v_id text := pg_catalog.lower(pg_catalog.regexp_replace(coalesce(p_external_id, ''), '\s', '', 'g'));
  v_count integer;
  v_match uuid;
begin
  if v_email = '' or v_id = '' or pg_catalog.length(v_email) > 320 or pg_catalog.length(v_id) > 80 then
    return null;
  end if;

  select pg_catalog.count(*)::integer, (pg_catalog.array_agg(r.id))[1]
  into v_count, v_match
  from public.requesters r
  where r.kind in ('student', 'staff')
    and r.archived_at is null
    and r.email is not null
    and pg_catalog.lower(r.email) = v_email
    and pg_catalog.lower(coalesce(r.external_id, '')) = v_id;

  if v_count = 1 then
    return v_match;
  end if;
  return null;
end;
$$;

