-- ---------------------------------------------------------------------------
-- Forms: the sign-up sheet, the permission slip and the check-in, kept against
-- the directory instead of beside it.
--
-- A skills officer running a trip does this today: a Google Form, a Google
-- Sheet behind it, and an afternoon of copying names out of one and into a
-- roster, matching "Jordan R." to an OSIS by hand. Every respondent retypes
-- facts the school already holds — their own name, their class, their
-- guardian's phone — and half of them get one of those wrong.
--
-- This is that form, with three differences that are the whole point:
--
--   * A DIRECTORY FIELD is a question the directory already knows the answer
--     to. The respondent proves who they are once (school email AND OSIS or
--     staff id, both on the same record) and those questions arrive filled in,
--     editable, so a guardian's new number is a correction rather than a
--     retype. What they change is recorded as changed, so the officer can see
--     which answers disagree with the directory.
--   * A LINKED GROUP turns a matched response into a roster row: the trip's
--     sign-up form fills the trip's roster. A LINKED EVENT marks the matched
--     respondent present, which is what a check-in form is.
--   * The PUBLIC LINK is `/f/<slug>`, reached by somebody with no account at
--     all. Everything it can do goes through the four `app_public_form*`
--     functions below, granted to `anon`; `anon` holds no privilege on any
--     table here, and those functions answer as little as the page needs.
--
-- WHAT THE PUBLIC NEVER SEES. A guardian's phone number is never returned to
-- an anonymous caller, not even to the respondent it belongs to: the prefill
-- carries it masked to its last four digits ("••• ••• 1234"), and a respondent
-- who keeps it sends back "keep", which the database resolves to the number on
-- file. An address is never read at all. The identity check says the same
-- thing — "no match" — whether the email was wrong, the id was wrong or both,
-- so it cannot be used to learn which addresses are real.
--
-- ABUSE. The slug is 12 characters from a 31-letter alphabet, about 59 bits,
-- generated here and never chosen by a person, so a form cannot be found by
-- guessing. Failed identity checks are counted per form, per caller and per
-- form overall, and past either ceiling the form stops answering identity
-- questions for fifteen minutes. The caller key is a SHA-256 of the client
-- address the application server forwards (`x-edison-client`), or of the first
-- `x-forwarded-for` hop; it is never stored in the clear. A caller who forges
-- that header only moves between per-caller buckets — the per-form ceiling
-- holds regardless, and it is the one that bounds a brute force. Payloads are
-- capped (200 KB of answers, 60 questions, a signature of 20,000 characters),
-- and a closed or full form refuses a new response in the database, not only
-- on the page.
--
-- WHO MAY DO WHAT. Any active account may make a form: the skills officer is
-- the main audience, and a form that needed an administrator would be a Google
-- Form again by Friday. A form is SHARED by default, which means every active
-- account can see it, edit it and read its responses — the same openness a
-- group has. Its maker may unshare it, and then only the maker and an
-- administrator can reach it. Deleting a form and changing who sees it are the
-- maker's (or an administrator's), because those are the two acts somebody else
-- cannot undo for them.
--
-- NO DIRECT WRITES. Row-level security with SELECT policies only, SELECT
-- granted to `authenticated` and nothing to `anon`, and every change through a
-- SECURITY DEFINER function that re-derives the actor — or, for the public
-- functions, that re-checks the respondent's identity on every call.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Forms are a seventh thing the record history can be about.
-- ---------------------------------------------------------------------------

alter table public.record_events
