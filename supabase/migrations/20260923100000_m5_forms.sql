create or replace function public.app_form_slug()
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  -- No 0/o, 1/l/i: a slug is read off a poster and typed into a phone.
  v_alphabet constant text := 'abcdefghjkmnpqrstuvwxyz23456789';
  v_bytes bytea := extensions.gen_random_bytes(12);
  v_slug text := '';
  i integer;
begin
  for i in 0..11 loop
    v_slug := v_slug || pg_catalog.substr(v_alphabet, (pg_catalog.get_byte(v_bytes, i) % 31) + 1, 1);
  end loop;
  return v_slug;
end;
$$;

