-- ---------------------------------------------------------------------------
-- The kiosk: a signed-in device at a door.
--
-- The account holding the device vouches for the lookup, so an id or an email
-- alone is enough — the same matching rules as app_mark_attendance_by_key.
-- ---------------------------------------------------------------------------

create or replace function public.app_form_kiosk_identify(p_form uuid, p_key text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor public.app_accounts;
  v_form public.forms;
  v_key text;
  v_count integer;
  v_id uuid;
  v_person public.requesters;
  v_prefill jsonb;
begin
  v_actor := public.app_require_actor();

  select * into v_form from public.forms f where f.id = p_form;
  if not found or not public.app_form_can_see(v_form) then
    raise exception 'There is no form with that id.' using errcode = 'check_violation';
  end if;
  if public.app_form_state(v_form) = 'closed' then
    return pg_catalog.jsonb_build_object('outcome', 'closed');
  end if;

  v_key := pg_catalog.btrim(coalesce(p_key, ''));
  if v_key = '' then
    raise exception 'Scan a card, or type an OSIS, staff id or name.' using errcode = 'check_violation';
  end if;

  with hits as (
    select
      r.id,
      case
        when pg_catalog.lower(coalesce(r.external_id, '')) = pg_catalog.lower(v_key) then 1
        when r.email is not null and pg_catalog.lower(r.email) = pg_catalog.lower(v_key) then 1
        else 2
      end as rank
    from public.requesters r
    where r.kind in ('staff', 'student')
      and (
        pg_catalog.lower(coalesce(r.external_id, '')) = pg_catalog.lower(v_key)
        or (r.email is not null and pg_catalog.lower(r.email) = pg_catalog.lower(v_key))
        or pg_catalog.lower(r.display_name) = pg_catalog.lower(v_key)
      )
  ),
  best as (select pg_catalog.min(h.rank) as rank from hits h)
  select pg_catalog.count(*)::integer, (pg_catalog.array_agg(h.id))[1]
  into v_count, v_id
  from hits h
  join best b on b.rank = h.rank;

  if coalesce(v_count, 0) = 0 then
    return pg_catalog.jsonb_build_object('outcome', 'no_match');
  end if;
  if v_count > 1 then
    return pg_catalog.jsonb_build_object('outcome', 'ambiguous');
  end if;

  select * into v_person from public.requesters r where r.id = v_id;
  v_prefill := public.app_form_prefill(v_form, v_person);

  return pg_catalog.jsonb_build_object(
    'outcome', 'match',
    'requester_id', v_person.id,
    'first_name', public.app_form_first_name(v_person),
    'prefill', v_prefill -> 'prefill',
    'masked', v_prefill -> 'masked',
    'already', exists (
      select 1 from public.form_responses r
      where r.form_id = v_form.id and r.requester_id = v_person.id
    )
  );
end;
$$;

