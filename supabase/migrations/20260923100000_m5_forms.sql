/*
 * The identity step. Answers a JSON object and never raises for a wrong
 * identity, because a raise would roll back the row that counts it.
 *
 *   {ok: true, first_name, prefill, masked, already}
 *   {ok: false, reason: 'missing' | 'closed' | 'not_needed' | 'incomplete' | 'no_match' | 'throttled'}
 */
create or replace function public.app_public_form_identify(
  p_slug text,
  p_email text,
  p_external_id text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_form public.forms;
  v_key text;
  v_match uuid;
  v_person public.requesters;
  v_prefill jsonb;
begin
  if p_slug is null or p_slug !~ '^[a-z0-9]{12}$' then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'missing');
  end if;
  select * into v_form from public.forms f where f.slug = p_slug;
  if not found then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'missing');
  end if;
  if public.app_form_state(v_form) = 'closed' then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'closed');
  end if;
  if v_form.audience <> 'directory' then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'not_needed');
  end if;
  if pg_catalog.btrim(coalesce(p_email, '')) = '' or pg_catalog.btrim(coalesce(p_external_id, '')) = '' then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'incomplete');
  end if;

  v_key := public.app_form_client_key();

  -- The window slides: a day of history is more than the fifteen minutes
  -- counted, and pruning here keeps the table the size of one busy morning.
  delete from public.form_identity_attempts a
  where a.form_id = v_form.id and a.at < pg_catalog.now() - interval '1 day';

  if public.app_form_throttled(v_form.id, v_key, 'miss') then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'throttled');
  end if;

  v_match := public.app_form_match_identity(p_email, p_external_id);
  if v_match is null then
    insert into public.form_identity_attempts (form_id, client_key, kind)
    values (v_form.id, v_key, 'miss');
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'no_match');
  end if;

  select * into v_person from public.requesters r where r.id = v_match;
  v_prefill := public.app_form_prefill(v_form, v_person);

  return pg_catalog.jsonb_build_object(
    'ok', true,
    'first_name', public.app_form_first_name(v_person),
    'prefill', v_prefill -> 'prefill',
    'masked', v_prefill -> 'masked',
    'already', exists (
      select 1 from public.form_responses r
      where r.form_id = v_form.id and r.requester_id = v_person.id
    )
  );
end;
$$;

comment on function public.app_public_form_identify(text, text, text) is
  'Public: the identity step of a directory form. Both the school email and the OSIS or staff id must name the same directory record; a miss is counted against the caller and the form and answered with the same no_match whichever half was wrong. On a match, answers the first name and the directory values for this form''s directory questions only, with a guardian phone masked to its last four digits.';

/*
 * The public submit. Identity is checked again — nothing about the earlier
 * step is trusted — and a closed or full form refuses a new response here, in
 * the database, whatever the page believed.
 *
 *   {ok: true, updated, first_name}
 *   {ok: false, reason: 'missing' | 'closed' | 'full' | 'no_match' | 'throttled'}
 *
 * An answer that does not fit its question raises, with a sentence naming the
 * question: nothing is stored and nothing needs keeping.
 */
create or replace function public.app_public_form_submit(
  p_slug text,
  p_email text,
  p_external_id text,
  p_answers jsonb
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_form public.forms;
  v_state text;
  v_key text;
  v_match uuid;
  v_person public.requesters;
  v_clean jsonb;
  v_result jsonb;
begin
  if p_slug is null or p_slug !~ '^[a-z0-9]{12}$' then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'missing');
  end if;
  -- Locked, so two responses arriving together cannot both be the last one
  -- under the cap.
  select * into v_form from public.forms f where f.slug = p_slug for update;
  if not found then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'missing');
  end if;

  v_state := public.app_form_state(v_form);
  if v_state = 'closed' then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'closed');
  end if;

  v_key := public.app_form_client_key();

  if v_form.audience = 'directory' then
    if public.app_form_throttled(v_form.id, v_key, 'miss') then
      return pg_catalog.jsonb_build_object('ok', false, 'reason', 'throttled');
    end if;
    v_match := public.app_form_match_identity(p_email, p_external_id);
    if v_match is null then
      insert into public.form_identity_attempts (form_id, client_key, kind)
      values (v_form.id, v_key, 'miss');
      return pg_catalog.jsonb_build_object('ok', false, 'reason', 'no_match');
    end if;
    select * into v_person from public.requesters r where r.id = v_match;
  else
    if public.app_form_throttled(v_form.id, v_key, 'submit') then
      return pg_catalog.jsonb_build_object('ok', false, 'reason', 'throttled');
    end if;
  end if;

  -- Full refuses a NEW response. Somebody correcting the one they already
  -- sent is not taking a place.
  if v_state = 'full' and not (
    v_person.id is not null and exists (
      select 1 from public.form_responses r
      where r.form_id = v_form.id and r.requester_id = v_person.id
    )
  ) then
    return pg_catalog.jsonb_build_object('ok', false, 'reason', 'full');
  end if;

  v_clean := public.app_form_clean_answers(v_form, p_answers, v_person);

  if v_form.audience <> 'directory' then
    insert into public.form_identity_attempts (form_id, client_key, kind)
    values (v_form.id, v_key, 'submit');
  end if;

  v_result := public.app_form_record_response(v_form, v_person.id, v_clean, 'link', null);

  return pg_catalog.jsonb_build_object(
    'ok', true,
    'updated', (v_result ->> 'updated')::boolean,
    'first_name', case when v_person.id is not null then public.app_form_first_name(v_person) end
  );
end;
$$;

comment on function public.app_public_form_submit(text, text, text, jsonb) is
  'Public: sends one response to an open form. A directory form re-checks the email and id on every call; an anyone form is throttled per caller and per form. Refuses a closed form, and a full one unless the respondent is replacing their own earlier answers. Adds a matched respondent to the linked group and marks them present at the linked event.';

