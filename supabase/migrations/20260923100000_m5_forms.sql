create or replace function public.app_create_form(
  p_title text,
  p_description text default '',
  p_fields jsonb default '[]'::jsonb,
  p_audience text default 'directory'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor public.app_accounts;
  v_title text;
  v_fields jsonb;
  v_id uuid;
  v_try integer := 0;
begin
  v_actor := public.app_require_actor();

  v_title := pg_catalog.btrim(coalesce(p_title, ''));
  if v_title = '' then
    raise exception 'Give the form a title.' using errcode = 'check_violation';
  end if;
  if pg_catalog.length(v_title) > 120 then
    raise exception 'A form title is 120 characters at most.' using errcode = 'check_violation';
  end if;
  if coalesce(p_audience, 'directory') not in ('directory', 'anyone') then
    raise exception 'Choose who can answer: directory or anyone.' using errcode = 'check_violation';
  end if;
  v_fields := public.app_form_clean_fields(p_fields);

  -- A collision in 59 bits is not going to happen; if it does, draw again.
  loop
    v_try := v_try + 1;
    begin
      insert into public.forms (slug, title, description, fields, audience, created_by)
      values (
        public.app_form_slug(),
        v_title,
        pg_catalog.left(pg_catalog.btrim(coalesce(p_description, '')), 2000),
        v_fields,
        coalesce(p_audience, 'directory'),
        v_actor.id
      )
      returning id into v_id;
      exit;
    exception
      when unique_violation then
        if v_try >= 5 then
          raise;
        end if;
    end;
  end loop;

  perform public.app_log_record_event('form', v_id, 'form_created', v_actor.id, 'Form created: ' || v_title);
  return v_id;
end;
