create table if not exists public.forms (
  id uuid primary key default extensions.gen_random_uuid(),
  -- The public address. Generated by app_form_slug(), never typed: a slug a
  -- person chose is a slug a person can guess.
  slug text not null unique check (slug ~ '^[a-z0-9]{12}$'),
  title text not null check (pg_catalog.length(pg_catalog.btrim(title)) between 1 and 120),
  description text not null default '' check (pg_catalog.length(description) <= 2000),
  -- The questions, in order, as app_form_clean_fields() leaves them. One
  -- document rather than a child table because the builder saves the whole
  -- form at once and a response is read against the whole list.
  fields jsonb not null default '[]'::jsonb check (pg_catalog.jsonb_typeof(fields) = 'array'),
  is_open boolean not null default true,
  closes_at timestamptz,
  response_cap integer check (response_cap is null or response_cap between 1 and 10000),
  audience text not null default 'directory' check (audience in ('directory', 'anyone')),
  -- SET NULL on both: a trip roster that is deleted does not take the sign-up
  -- form with it, it simply stops filling a roster.
  group_id uuid references public.people_groups (id) on delete set null,
  event_id uuid references public.group_events (id) on delete set null,
  shared boolean not null default true,
  created_by uuid references public.app_accounts (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.forms is
  'A form: questions, some of them answered from the directory, reached publicly at /f/<slug> or at a signed-in kiosk. Written only by the app_*form* functions.';
comment on column public.forms.fields is
  'Ordered questions: {id, type, label, help, required, options?, directory?}. Types: short_text, long_text, single_choice, multi_choice, dropdown, number, date, yes_no, signature, directory. Cleaned by app_form_clean_fields().';
comment on column public.forms.audience is
  'directory: a respondent proves who they are with school email and OSIS or staff id before answering. anyone: no identity step; responses are anonymous unless taken at a kiosk.';
comment on column public.forms.shared is
  'Whether every active account can see and edit the form and read its responses. When false, only its maker and administrators can.';

create index if not exists forms_updated_idx on public.forms (updated_at desc);

create table if not exists public.form_responses (
  id uuid primary key default extensions.gen_random_uuid(),
  form_id uuid not null references public.forms (id) on delete cascade,
  -- SET NULL: the answers outlive a directory record that is removed, and the
  -- screen shows them as unmatched rather than losing them.
  requester_id uuid references public.requesters (id) on delete set null,
  answers jsonb not null default '{}'::jsonb check (pg_catalog.jsonb_typeof(answers) = 'object'),
  -- The directory questions whose answer the respondent changed from what
  -- the directory holds. A list of question ids.
  changed text[] not null default '{}',
  via text not null check (via in ('link', 'kiosk')),
  -- The signed-in account whose kiosk took the response. NULL for the link.
  recorded_by uuid references public.app_accounts (id),
  submitted_at timestamptz not null default now()
);

comment on table public.form_responses is
  'One response to one form. A directory-matched respondent has at most one per form: answering again replaces their earlier answers. Written only by the submit functions and deleted only by app_delete_form_response.';

create index if not exists form_responses_form_idx
  on public.form_responses (form_id, submitted_at desc);

-- One response per person per form. Answering again is a correction, not a
-- second sign-up, and a roster built from a form must not list anybody twice.
create unique index if not exists form_responses_one_per_person
  on public.form_responses (form_id, requester_id)
  where requester_id is not null;

create index if not exists form_responses_requester_idx
  on public.form_responses (requester_id);

/*
 * The throttle's memory. `kind` is 'miss' for an identity check that matched
 * nobody and 'submit' for a response to an open (`anyone`) form. Rows older
 * than a day are pruned by the next identity check on the same form, so this
 * table is a sliding window, not a log.
 */
create table if not exists public.form_identity_attempts (
  form_id uuid not null references public.forms (id) on delete cascade,
  client_key text not null,
  kind text not null check (kind in ('miss', 'submit')),
  at timestamptz not null default now()
);

comment on table public.form_identity_attempts is
  'Recent failed identity checks and open-form submissions, per form and per hashed client address, for the public throttle. Never readable by any client role.';

create index if not exists form_identity_attempts_idx
  on public.form_identity_attempts (form_id, kind, at);

