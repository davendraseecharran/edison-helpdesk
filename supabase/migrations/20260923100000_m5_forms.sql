      event_id = p_event,
      shared = v_shared,
      updated_at = pg_catalog.now()
  where f.id = p_form;

  if v_open <> v_form.is_open then
    perform public.app_log_record_event(
      'form', p_form,
      case when v_open then 'form_opened' else 'form_closed' end,
      v_actor.id,
      case when v_open then 'Form opened: ' else 'Form closed: ' end || v_form.title
