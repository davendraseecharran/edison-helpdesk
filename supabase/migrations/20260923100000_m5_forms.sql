/* What the command palette finds by title. */
create or replace function public.app_search_forms(p_query text, p_limit integer default 8)
returns table (
  id uuid,
  title text,
  subtitle text,
  meta text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_query text := pg_catalog.btrim(coalesce(p_query, ''));
  v_pattern text;
begin
  perform public.app_require_actor();
  if pg_catalog.length(v_query) < 2 then
    return;
  end if;
  -- LIKE's own wildcards are matched literally.
  v_pattern := '%' || pg_catalog.replace(pg_catalog.replace(pg_catalog.replace(
    pg_catalog.lower(v_query), '\', '\\'), '%', '\%'), '_', '\_') || '%';

  return query
    select
      f.id,
      f.title,
      nullif(pg_catalog.left(f.description, 120), ''),
      (select pg_catalog.count(*)::integer from public.form_responses r where r.form_id = f.id)::text
        || case
             when (select pg_catalog.count(*) from public.form_responses r where r.form_id = f.id) = 1
               then ' response' else ' responses'
           end
    from public.forms f
    where public.app_form_can_see(f)
      and pg_catalog.lower(f.title) like v_pattern
    order by (pg_catalog.lower(f.title) like pg_catalog.lower(v_query) || '%') desc, f.updated_at desc
    limit greatest(1, least(coalesce(p_limit, 8), 25));
end;
$$;

comment on function public.app_search_forms(text, integer) is
  'Forms the caller may see whose title contains the query, titles that start with it first. At most 25.';

