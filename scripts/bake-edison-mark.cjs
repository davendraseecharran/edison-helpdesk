#!/usr/bin/env node
/**
 * Bakes the Edison bulb — the sign-in screen's mark — into the point cloud
 * `thinking-logos` animates, and writes it to
 * `src/components/ui/edison-mark.baked.ts`.
 *
 * The same reasoning as `bake-openai-mark.cjs`, which this copies: baking at
 * run time is a canvas, an image decode and a Poisson sampler on the main
 * thread before a loading state can draw its first frame, so it happens once
 * here and the result is checked in. Run it by hand when the bulb's artwork
 * in `src/components/auth/AuthFrame.tsx` changes; the two must stay the same
 * drawing.
 *
 *   PLAYWRIGHT_MODULE=/path/to/node_modules/playwright \
 *   node scripts/bake-edison-mark.cjs
 *
 * The bulb is three strokes, and a stroke 1.5 units wide in a 48-unit box is
 * a hairline no sampler can put dots on. The strokes are thickened for the
 * bake only, so the dots have a body to sit in; what comes out is the same
 * silhouette.
 */

/* eslint-disable @typescript-eslint/no-require-imports -- Standalone Node/Playwright runner, outside the bundler. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
/* eslint-enable @typescript-eslint/no-require-imports */

const root = path.resolve(__dirname, '..');

/** The bulb from `AuthFrame.tsx`, with its strokes thickened for sampling. */
const BULB_SVG = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="4 1 40 44" width="400" height="440">
  <g fill="none" stroke="#000" stroke-linecap="round" stroke-linejoin="round">
    <path stroke-width="3.4" d="M15 28.2 A13.5 13.5 0 1 1 33 28.2 C31 30 29.5 31.6 29.5 34.5 L18.5 34.5 C18.5 31.6 17 30 15 28.2 Z"/>
    <path stroke-width="2.8" d="M20 34.5 V29 L22 25.5 L24 29 L26 25.5 L28 29 V34.5"/>
    <path stroke-width="3.4" d="M18.5 38.5 H29.5 M20 42 H28"/>
  </g>
</svg>`;

/**
 * Two sets, as for the OpenAI mark: dots need about two pixels of pitch to
 * resolve, so the small inline rendering and the empty-state rendering are
 * separate designs rather than one scaled.
 */
const SETS = [
  { name: 'BULB_SMALL', renderedAt: 24, count: 130, style: 'fill', shell: 'flat', depth: 0.08 },
  { name: 'BULB_LARGE', renderedAt: 56, count: 360, style: 'fill', shell: 'dome', depth: 0.3 },
];

async function main() {
  const bundle = fs.readFileSync(
    path.join(root, 'node_modules', 'thinking-logos', 'dist', 'bake.es.js'),
    'utf8',
  );

  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent('<!doctype html><meta charset="utf-8"><title>bake</title>');
  const baked = await page.evaluate(
    async ({ bundleSource, svg, sets }) => {
      const url = URL.createObjectURL(new Blob([bundleSource], { type: 'text/javascript' }));
      const { bakeLogo, serializeLogo } = await import(/* webpackIgnore: true */ url);
      const out = {};
      for (const set of sets) {
        const points = await bakeLogo(
          { svg },
          {
            count: set.count,
            style: set.style,
            shell: set.shell,
            depth: set.depth,
            resolution: 512,
            seed: 11,
          },
        );
        out[set.name] = serializeLogo(points);
      }
      URL.revokeObjectURL(url);
      return out;
    },
    { bundleSource: bundle, svg: BULB_SVG, sets: SETS },
  );
  await browser.close();

  const header = `// Generated by scripts/bake-edison-mark.cjs — do not edit by hand.
//
// The Edison bulb (the sign-in mark), baked into the point cloud
// \`thinking-logos\` animates, so the application's own loading language is
// its own mark rather than a provider's. Checked in, so nothing rasterises at
// run time.
//
// Two sets, because dots need roughly two pixels of pitch to resolve as
// separate marks: ${SETS.map((s) => `${s.count} for ${s.renderedAt}px`).join(', ')}.

import { deserializeLogo } from 'thinking-logos/bake';
import type { LogoPointSet } from 'thinking-logos';
`;

  const body = SETS.map((set) => {
    const json = JSON.stringify(baked[set.name]);
    return `
/** The bulb at ${set.count} dots, for the ${set.renderedAt}px rendering. */
export const ${set.name}: LogoPointSet = deserializeLogo(
  ${json},
);`;
  }).join('\n');

  const file = path.join(root, 'src', 'components', 'ui', 'edison-mark.baked.ts');
  fs.writeFileSync(file, `${header}${body}\n`);
  const size = fs.statSync(file).size;
  process.stdout.write(`wrote ${path.relative(root, file)} (${Math.round(size / 1024)} kB)\n`);
}

main().catch((error) => {
  process.stderr.write(`${error && error.stack ? error.stack : error}\n`);
  process.exit(1);
});
